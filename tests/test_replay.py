FIXTURE = Path(__file__).parent / 'fixtures/saved-decision-v1-7a38141.json'
FIXTURE_SHA256 = '28a9fdc931f8c6fdb19b099218d4204d45522dee86d6b936c6ea7016d648a4f1'


def _saved():
    return json.loads(FIXTURE.read_bytes())


def _change(saved, path, value):
    target = saved
    for key in path[:-1]:
        target = target[key]
    target[path[-1]] = value
    return saved


def _shoe(cards):
    return tuple(cards.count(rank) for rank in RANKS)


def _forbid_calculation(monkeypatch):
    def forbidden(*args, **kwargs):
        pytest.fail('record was not refused before calculation')
    monkeypatch.setattr(record, 'best_action', forbidden)


def test_immutable_pre_consumer_schema_v1_fixture():
    # Emitted on 2026-10-08 from exact old source 7a38141, not regenerated by
    # the candidate exporter. Private provenance retains the source hashes.
    raw = FIXTURE.read_bytes()
    assert hashlib.sha256(raw).hexdigest() == FIXTURE_SHA256
    assert replay.replay_json(raw)['status'] == 'agreement'


@pytest.mark.parametrize('cards,up,unseen,s17', CASES)
def test_recompute_uses_independent_tiny_physical_reference(cards, up, unseen, s17):
    saved = record.decision_json(cards, up, replace(STANDARD, s17=s17), shoe=_shoe(unseen))
    result = replay.replay_json(saved)
    expected = physical_reference(cards, up, unseen, s17=s17)
    assert result['status'] == 'agreement'
    assert result['recomputed']['evs'] == pytest.approx(
        {key: float(value) for key, value in expected.items()}, rel=0, abs=1e-12)
    assert result['comparison']['legal_actions']['matches']
    assert result['comparison']['recommendation']['matches']
    assert result['comparison']['margin']['matches']


def test_fresh_origin_retains_counts_and_never_removes_visible_cards_again(monkeypatch):
    saved = record.decision_record('A,T', '9', replace(STANDARD, decks=1, blackjack_payout=1.25))
    expected = tuple(saved['state']['shoe']['counts'])
    original = record.best_action
    calls = []

    def checked(cards, up, *, shoe, rules, is_split_hand, hand_count,
                can_double, can_split):
        calls.append((cards, up, shoe, rules, is_split_hand, hand_count))
        assert shoe == expected
        return original(cards, up, shoe=shoe, rules=rules,
                        is_split_hand=is_split_hand, hand_count=hand_count,
                        can_double=can_double, can_split=can_split)

    monkeypatch.setattr(record, 'best_action', checked)
    result = replay.replay_json(json.dumps(saved))
    assert result['status'] == 'agreement'
    assert len(calls) == 1
    assert result['recomputed']['evs'] == {'S': 1.25}


