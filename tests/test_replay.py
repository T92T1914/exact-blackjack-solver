def test_file_read_is_bounded_and_does_not_change_bytes(tmp_path, monkeypatch):
    path = tmp_path / 'saved.json'
    original = FIXTURE.read_bytes()
    path.write_bytes(original)
    before = path.stat().st_mtime_ns
    assert replay.replay_file(path)['status'] == 'agreement'
    assert path.read_bytes() == original and path.stat().st_mtime_ns == before
    reads = []

    class Stream(io.BytesIO):
        def read(self, size=-1):
            reads.append(size)
            return super().read(size)

    monkeypatch.setattr(replay, 'open', lambda *a: Stream(b' ' * (replay.MAX_RECORD_BYTES + 10)),
                        raising=False)
    assert replay.replay_file(path)['status'] == 'invalid_input'
    assert reads == [replay.MAX_RECORD_BYTES + 1]


